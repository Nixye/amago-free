import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
const source=readFileSync(new URL('../dist/workspace-productivity.js',import.meta.url),'utf8');
const ctx=vm.createContext({vault:{},workbench:{source:'vault'},console});
vm.runInContext(source.slice(0,source.indexOf('const productivityProjectTree')),ctx);
assert.equal(ctx.productivityWorkspaceKey(),'vault');
const prefs=ctx.productivityPreferences();prefs.searches.push({query:'#ideia'});prefs.sort='updated';
ctx.workbench={source:'project',project:{root:'C:/Notas'}};
assert.equal(ctx.productivityPreferences().searches.length,0);
ctx.productivityPreferences().searches.push({query:'name:Projeto'});
ctx.workbench.project.root='C:/Outra';assert.equal(ctx.productivityPreferences().searches.length,0);
ctx.workbench={source:'vault'};assert.equal(ctx.productivityPreferences().searches[0].query,'#ideia');
const input=[{name:'Nota 10',updated:'2026-01-01'},{name:'Notas',kind:'directory',updated:'2025-01-01'},{name:'Nota 2',updated:'2026-02-01'},{name:'A',updated:'invalid'}];
assert.deepEqual(Array.from(ctx.productivitySort(input,'name'),e=>e.name),['Notas','A','Nota 2','Nota 10']);
assert.deepEqual(Array.from(ctx.productivitySort(input,'name-desc'),e=>e.name),['Notas','Nota 10','Nota 2','A']);
assert.deepEqual(Array.from(ctx.productivitySort(input,'updated'),e=>e.name),['Notas','Nota 2','Nota 10','A']);
assert.equal(input[0].name,'Nota 10');
ctx.vault.productivity={workspaces:'invalid'};assert.equal(ctx.productivityPreferences().searches.length,0);
console.log('Workspace productivity: isolated preferences, natural sorting, folders first and invalid metadata fallback passed.');
