import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),N=require('../dist/document-navigation-core.js');
assert.deepEqual(N.find('a.* A.*','a.*').matches,[{start:0,end:3},{start:4,end:7}]);
assert.equal(N.find('a.* A.*','a.*',true).total,1);
assert.equal(N.find('ação AÇÃO','ação').total,2);
assert.equal(N.find('aaaa','aa').total,2);
assert.equal(N.find('abc','').total,0);
assert.deepEqual(N.replaceAll('x x','x','$&'),{text:'$& $&',count:2});
assert.deepEqual(N.replaceAll('x x','x',''),{text:' ',count:2});
assert.deepEqual(N.replaceAll('x X','x','a',true),{text:'a X',count:1});
assert.equal(N.replaceAt('abc','a','x',{start:1,end:2}),null);
assert.deepEqual(N.replaceAt('abc','b','long',{start:1,end:2}),{text:'alongc',start:1,end:5});
const bounded=N.find('x'.repeat(6000),'x');assert.equal(bounded.total,6000);assert.equal(bounded.matches.length,5000);assert(bounded.truncated);
const markdown='\uFEFF---\r\n# hidden property\r\n---\r\n# First\r\n## **Second** ##\r\n```md\r\n### code\r\n```\r\n<!--\r\n#### html comment\r\n-->\r\n%%\r\n##### private\r\n%%\r\n###### Last\r\n####### invalid\r\n    # indented\r\n#literal\r\n';
const headings=N.headings(markdown);assert.deepEqual(headings.map(h=>h.title),['First','**Second**','Last']);assert.deepEqual(headings.map(h=>h.level),[1,2,6]);assert.equal(headings[0].line,4);assert.equal(markdown.slice(headings[2].start,headings[2].end),'###### Last');
assert.equal(N.headings('````\n```\n\n# hidden\n````\n# shown').length,1);
assert.equal(N.headings('~~~\n# hidden\n~~~\n# shown').length,1);
assert.equal(N.headings('`<!--`\n# shown').length,1);
assert.equal(N.headings('<!-- # hidden -->\n# shown').length,1);
assert.equal(N.headings('%% # hidden %%\n# shown').length,1);
assert.equal(N.headings('---\n# front without closer').length,0);
console.log('Document navigation: literal/case search, bounded matches, safe replacement, stale ranges and heading offsets/exclusions passed.');
